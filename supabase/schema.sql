-- Lenscape optional cloud leaderboard schema.
-- The web app works locally without Supabase. This schema enables a shared,
-- server-written leaderboard. Browser roles intentionally have no table access.

create table if not exists public.explorers (
  id text primary key,
  display_name text not null default 'Explorer' check (char_length(display_name) between 1 and 50),
  username text not null default 'explorer' check (char_length(username) between 1 and 30),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.discoveries (
  id bigint generated by default as identity primary key,
  explorer_id text not null references public.explorers(id) on delete cascade,
  landmark_key text not null,
  landmark_name text not null,
  city text not null default '',
  country text not null default '',
  lat double precision check (lat is null or lat between -90 and 90),
  lng double precision check (lng is null or lng between -180 and 180),
  verification_hash text,
  created_at timestamptz not null default now(),
  constraint discoveries_explorer_landmark_unique unique (explorer_id, landmark_key)
);

-- Safe to re-run against an earlier Lenscape schema.
alter table public.discoveries add column if not exists verification_hash text;
create unique index if not exists discoveries_verification_hash_unique
  on public.discoveries(verification_hash)
  where verification_hash is not null;
create index if not exists discoveries_explorer_idx on public.discoveries(explorer_id);
create index if not exists discoveries_city_idx on public.discoveries(city, country);

alter table public.explorers enable row level security;
alter table public.discoveries enable row level security;

-- Browser clients never talk to these tables directly. Only the server-side
-- /api/social function uses a service/secret key, which bypasses RLS.
revoke all on table public.explorers from anon, authenticated;
revoke all on table public.discoveries from anon, authenticated;
grant select, insert, update, delete on table public.explorers to service_role;
grant select, insert, update, delete on table public.discoveries to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace view public.leaderboard_stats
with (security_invoker = true)
as
select
  e.id,
  e.display_name,
  e.username,
  count(d.id)::int as unique_landmarks,
  count(distinct case
    when nullif(btrim(d.city), '') is not null
      then lower(btrim(d.city)) || '|' || lower(btrim(d.country))
    else null
  end)::int as cities,
  count(distinct nullif(lower(btrim(d.country)), ''))::int as countries
from public.explorers e
left join public.discoveries d on d.explorer_id = e.id
group by e.id, e.display_name, e.username;

revoke all on table public.leaderboard_stats from anon, authenticated;
grant select on table public.leaderboard_stats to service_role;
